import type { WordPair } from '../types'

function pair(
  civilian: string,
  undercover: string,
  category: string,
  difficulty: WordPair['difficulty'],
): WordPair {
  const slug = `${civilian}-${undercover}`
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
  return { id: `default-${slug}`, civilian, undercover, category, difficulty }
}

